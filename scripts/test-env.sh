#!/usr/bin/env bash
#
# Test environment management for home-server-provisioner.
#
# Reads VM definitions from scripts/test-vms.conf and manages
# Multipass VMs + Ansible test inventory.
#
# Usage:
#   ./scripts/test-env.sh create   - Launch VMs and generate inventory
#   ./scripts/test-env.sh destroy  - Delete all VMs and clean up inventory
#   ./scripts/test-env.sh status   - Show current VM state

set -euo pipefail

# --- Configuration ---

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
VM_CONF="$SCRIPT_DIR/test-vms.conf"
INVENTORY_FILE="$PROJECT_DIR/inventories/test/hosts.yml"
CLOUD_INIT_TMP="/tmp/hsp-cloud-init.yml"

# VM resource defaults (overridable via .env)
VM_CPUS="${VM_CPUS:-2}"
VM_MEMORY="${VM_MEMORY:-2G}"
VM_DISK="${VM_DISK:-20G}"
VM_IMAGE="${VM_IMAGE:-24.04}"

# All groups the project supports (used to build complete inventory)
ALL_GROUPS="app_servers backup_targets vpn_servers"

# --- Helper functions ---

die() { echo "Error: $1" >&2; exit 1; }

# Read VM definitions from config, skipping comments and blank lines
read_vms() {
    grep -v '^\s*#' "$VM_CONF" | grep -v '^\s*$'
}

# Find the user's SSH public key
detect_ssh_pubkey() {
    local key=""
    for candidate in "$HOME/.ssh/id_ed25519.pub" "$HOME/.ssh/id_rsa.pub" "$HOME/.ssh/id_ecdsa.pub"; do
        if [[ -f "$candidate" ]]; then
            key="$candidate"
            break
        fi
    done

    if [[ -z "$key" ]]; then
        die "No SSH public key found. Set SSH_PUBKEY_FILE in .env or create a key with ssh-keygen."
    fi

    echo "$key"
}

# Generate cloud-init YAML that injects the user's SSH key
create_cloud_init() {
    local pubkey_file="$1"
    cat > "$CLOUD_INIT_TMP" <<EOF
ssh_authorized_keys:
  - $(cat "$pubkey_file")
EOF
}

# Query a VM's IPv4 address (waits briefly for the IP to become available)
get_vm_ip() {
    local vm_name="$1"
    local ip=""
    local attempts=0

    while [[ -z "$ip" || "$ip" == "--" ]] && [[ $attempts -lt 30 ]]; do
        ip=$(multipass info "$vm_name" --format json 2>/dev/null \
            | grep -A1 '"ipv4"' \
            | grep -oE '[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+' \
            || true)
        if [[ -z "$ip" ]]; then
            sleep 2
            ((attempts++))
        fi
    done

    if [[ -z "$ip" ]]; then
        die "Could not get IP for VM '$vm_name' after 60 seconds."
    fi

    echo "$ip"
}

# --- Inventory generation ---

generate_inventory() {
    echo "Generating test inventory..."

    # Collect VM name, group, and IP into an associative structure
    # using simple arrays since bash associative arrays vary by version
    local vm_lines=""
    while IFS=: read -r vm_name vm_group; do
        local ip
        ip=$(get_vm_ip "$vm_name")
        vm_lines="${vm_lines}${vm_name}:${vm_group}:${ip}"$'\n'
    done < <(read_vms)

    # Write the inventory YAML
    cat > "$INVENTORY_FILE" <<EOF
# Auto-generated by scripts/test-env.sh - do not edit manually.
all:
  children:
    servers:
      children:
EOF

    for group in $ALL_GROUPS; do
        # Find VMs belonging to this group
        local hosts=""
        while IFS=: read -r vm_name vm_group vm_ip; do
            if [[ "$vm_group" == "$group" ]]; then
                hosts="${hosts}            ${vm_name}:\n              ansible_host: ${vm_ip}\n"
            fi
        done <<< "$vm_lines"

        if [[ -n "$hosts" ]]; then
            echo "        ${group}:" >> "$INVENTORY_FILE"
            echo "          hosts:" >> "$INVENTORY_FILE"
            echo -e "$hosts" >> "$INVENTORY_FILE"
        else
            echo "        ${group}:" >> "$INVENTORY_FILE"
            echo "          hosts: {}" >> "$INVENTORY_FILE"
        fi
    done

    echo "Inventory written to $INVENTORY_FILE"
}

# --- Commands ---

cmd_create() {
    local pubkey_file="${SSH_PUBKEY_FILE:-$(detect_ssh_pubkey)}"
    echo "Using SSH public key: $pubkey_file"

    create_cloud_init "$pubkey_file"

    while IFS=: read -r vm_name vm_group; do
        if multipass info "$vm_name" &>/dev/null; then
            echo "VM '$vm_name' already exists, skipping."
        else
            echo "Creating VM '$vm_name' (group: $vm_group)..."
            multipass launch "$VM_IMAGE" \
                --name "$vm_name" \
                --cpus "$VM_CPUS" \
                --memory "$VM_MEMORY" \
                --disk "$VM_DISK" \
                --cloud-init "$CLOUD_INIT_TMP"
        fi
    done < <(read_vms)

    rm -f "$CLOUD_INIT_TMP"

    generate_inventory
    echo ""
    echo "Done. Run 'make provision' to test your playbooks."
}

cmd_destroy() {
    while IFS=: read -r vm_name vm_group; do
        if multipass info "$vm_name" &>/dev/null; then
            echo "Destroying VM '$vm_name'..."
            multipass delete "$vm_name" --purge
        else
            echo "VM '$vm_name' not found, skipping."
        fi
    done < <(read_vms)

    rm -f "$INVENTORY_FILE"
    echo "Test inventory removed."
    echo "Done."
}

cmd_status() {
    echo "Defined VMs (from $VM_CONF):"
    echo ""
    printf "  %-20s %-20s %-15s %s\n" "NAME" "GROUP" "STATE" "IP"
    printf "  %-20s %-20s %-15s %s\n" "----" "-----" "-----" "--"

    while IFS=: read -r vm_name vm_group; do
        local state="not created"
        local ip="-"

        if multipass info "$vm_name" &>/dev/null; then
            state=$(multipass info "$vm_name" --format json 2>/dev/null \
                | grep -o '"state":\s*"[^"]*"' \
                | head -1 \
                | grep -o '"[^"]*"$' \
                | tr -d '"' \
                || echo "unknown")
            ip=$(get_vm_ip "$vm_name" 2>/dev/null || echo "-")
        fi

        printf "  %-20s %-20s %-15s %s\n" "$vm_name" "$vm_group" "$state" "$ip"
    done < <(read_vms)
}

# --- Main ---

case "${1:-}" in
    create)  cmd_create  ;;
    destroy) cmd_destroy ;;
    status)  cmd_status  ;;
    *)
        echo "Usage: $0 {create|destroy|status}"
        exit 1
        ;;
esac
